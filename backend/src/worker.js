// Worker API: session -> permission -> validation -> parameterized write -> response.
// Keeping these routes separate prevents worker functionality leaking into public APIs.
import express from 'express';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dogStatus } from './dog-status.js';

export const uploadDirectory = (env = process.env) => resolve(env.UPLOAD_DIR || fileURLToPath(new URL('../../data/uploads', import.meta.url)));
const parseDog = row => dogStatus(typeof row.data === 'string' ? JSON.parse(row.data) : row.data);
const fail = (status, message) => Object.assign(new Error(message), { status, workerError: true });
const date = value => value === '' || value == null ? null : /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0, 10) === value ? value : (() => { throw fail(400, 'Use a valid calendar date.'); })();
const text = (body, key, max, required = false) => {
  const value = body[key];
  if (typeof value !== 'string' || value.length > max || (required && !value.trim())) throw fail(400, `Check the ${key} field.`);
  return value.trim();
};

export function validateAnimal(body = {}, previous = {}) {
  const name = text(body, 'name', 80, true), breed = text(body, 'breed', 80, true);
  if (!['Small', 'Medium', 'Large'].includes(body.size) || !['Female', 'Male', 'Unknown'].includes(body.sex) || !['Low', 'Medium', 'High'].includes(body.energyLevel)) throw fail(400, 'Choose valid size, sex and energy options.');
  const ageMonths = Number(body.ageMonths);
  if (!['string', 'number'].includes(typeof body.ageMonths) || body.ageMonths === '' || !Number.isFinite(ageMonths) || ageMonths < 0 || ageMonths > 360) throw fail(400, 'Age must be between 0 and 360 months.');
  // Local image paths only. Uploaded names are generated by the server, not supplied filenames.
  const image = text(body, 'image', 240, true);
  if (!/^\/public\/(?:assets\/dogs\/profiles\/[a-z0-9-]+\.jpg(?:\?v=[a-z0-9-]+)?|uploads\/[a-f0-9-]+\.(?:jpg|png|webp))$/.test(image)) throw fail(400, 'Choose an animal photo or upload a JPEG, PNG or WebP.');
  const intakeDate = date(body.intakeDate);
  if (!intakeDate) throw fail(400, 'Enter the date the animal came into care.');
  const sponsorshipStartedAt = date(body.sponsorshipStartedAt), sponsorshipEndsAt = date(body.sponsorshipEndsAt);
  if (sponsorshipEndsAt && (!sponsorshipStartedAt || sponsorshipEndsAt <= sponsorshipStartedAt)) throw fail(400, 'Sponsorship end must be after its start.');
  if (!Array.isArray(body.personality) || body.personality.length > 12 || body.personality.some(v => typeof v !== 'string' || v.length > 160)) throw fail(400, 'Enter up to 12 short personality traits.');
  return {
    ...previous, name, breed, ageMonths, age: ageMonths < 12 ? `${ageMonths} months` : `${Math.round(ageMonths / 12 * 10) / 10} years`,
    size: body.size, sex: body.sex, energyLevel: body.energyLevel, image, intakeDate,
    overview: text(body, 'overview', 4000, true), story: text(body, 'story', 6000, true),
    location: text(body, 'location', 160, true), goodWithPeople: text(body, 'goodWithPeople', 250), goodWithAnimals: text(body, 'goodWithAnimals', 250),
    personality: body.personality.map(v => v.trim()).filter(Boolean),
    permanentAdoptionDate: date(body.permanentAdoptionDate), sponsorshipStartedAt, sponsorshipEndsAt,
    adoptionDate: null, adoptionModel: 'Virtual adoption', mock: false,
    revision: (Number(previous.revision) || 0) + 1, updatedAt: new Date().toISOString(),
  };
}

export function installWorker(app, db, session) {
  const router = express.Router();
  // Never accept a role from the browser/session payload: read current access on every request.
  router.use(async (req, res, next) => {
    try {
      const user = await session(req);
      if (!user) throw fail(401, 'Log in with your worker account.');
      let access;
      try { access = await db.prepare('SELECT role,granted_at FROM worker_access WHERE user_id=?').get(user.id); }
      catch (error) { if (error.code === 'ER_NO_SUCH_TABLE') throw fail(503, 'Worker setup is required. Ask the project administrator to run db:worker.'); throw error; }
      if (!access) throw fail(403, 'This account does not have worker access.');
      req.worker = { id: user.id, username: user.username, email: user.email, role: access.role, lastLoginAt: user.lastLoginAt };
      next();
    } catch (error) { next(error); }
  });
  const permission = roles => (req, _res, next) => roles.includes(req.worker.role) ? next() : next(fail(403, 'Your worker role cannot perform this action.'));
  const editor = permission(['admin', 'editor']), admin = permission(['admin']);
  const dogs = async () => (await db.prepare('SELECT data FROM dogs ORDER BY id').all()).map(parseDog);
  const requests = () => db.prepare(`SELECT c.id,c.dog_id,c.amount_cents,c.frequency,c.status,c.name,c.email,c.phone,c.created_at,
    r.status AS review_status,r.note AS review_note,r.reviewed_at
    FROM contributions c LEFT JOIN worker_reviews r ON r.contribution_id=c.id ORDER BY c.created_at DESC`).all();
  router.get('/session', (req, res) => res.json({ worker: req.worker }));
  router.get('/dashboard', async (_req, res) => {
    const [animals, contributions] = await Promise.all([dogs(), requests()]);
    const currentMonth = new Date().toISOString().slice(0, 7);
    res.json({ animals, requests: contributions, summary: {
      totalDogs: animals.filter(d => !d.archivedAt).length,
      successfulAdoptions: animals.filter(d => d.permanentAdoptionDate).length,
      pendingAdoptions: contributions.filter(c => c.dog_id && !c.review_status && c.status === 'pending_payment').length,
      monthlyDonations: contributions.filter(c => c.status === 'paid' && c.created_at.startsWith(currentMonth)).reduce((sum, c) => sum + Number(c.amount_cents), 0),
      newThisMonth: animals.filter(d => !d.archivedAt && d.intakeDate?.startsWith(currentMonth)).length,
    } });
  });
  router.get('/animals', async (_req, res) => res.json({ animals: await dogs() }));
  router.post('/animals', editor, async (req, res) => {
    const id = randomUUID(), dog = { ...validateAnimal(req.body), id };
    await db.prepare('INSERT INTO dogs (id,data) VALUES (?,?)').run(id, JSON.stringify(dog));
    res.status(201).json({ animal: dogStatus(dog) });
  });
  // Optimistic concurrency prevents two workers silently overwriting each other's edits.
  async function updateAnimal(req, res, archive = false) {
    const row = await db.prepare('SELECT data FROM dogs WHERE id=?').get(req.params.id);
    if (!row) throw fail(404, 'Animal not found.');
    const previous = parseDog(row), revision = Number(previous.revision) || 0;
    if (req.body.revision !== revision) throw fail(409, 'This animal changed since you opened it. Reload before saving.');
    const dog = archive ? { ...previous, archivedAt: req.body.archived ? new Date().toISOString() : null, revision: revision + 1 } : validateAnimal(req.body, previous);
    if (archive && typeof req.body.archived !== 'boolean') throw fail(400, 'Choose archive or restore.');
    const result = await db.prepare("UPDATE dogs SET data=? WHERE id=? AND COALESCE(JSON_UNQUOTE(JSON_EXTRACT(data,'$.revision')),'0')=?").run(JSON.stringify(dog), previous.id, String(revision));
    if (!result.affectedRows) throw fail(409, 'Another worker saved changes first. Reload before saving.');
    res.json({ animal: dogStatus(dog) });
  }
  router.put('/animals/:id', editor, (req, res) => updateAnimal(req, res));
  router.patch('/animals/:id/archive', editor, (req, res) => updateAnimal(req, res, true));
  router.post('/images', editor, express.raw({ type: ['image/jpeg', 'image/png', 'image/webp'], limit: '2mb' }), async (req, res) => {
    const bytes = req.body;
    if (!Buffer.isBuffer(bytes) || bytes.length < 12) throw fail(400, 'Upload a JPEG, PNG or WebP photo up to 2 MB.');
    const extension = bytes.subarray(0, 3).equals(Buffer.from([255, 216, 255])) ? 'jpg' : bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) ? 'png' : bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP' ? 'webp' : null;
    if (!extension) throw fail(400, 'Unsupported photo format. SVG and executable files are not accepted.');
    await mkdir(uploadDirectory(), { recursive: true });
    const filename = `${randomUUID()}.${extension}`;
    await writeFile(resolve(uploadDirectory(), filename), bytes, { flag: 'wx', mode: 0o644 });
    res.status(201).json({ image: `/public/uploads/${filename}` });
  });
  router.get('/requests', async (_req, res) => res.json({ requests: await requests() }));
  router.put('/requests/:id/review', editor, async (req, res) => {
    if (!['reviewed', 'approved', 'declined'].includes(req.body.status)) throw fail(400, 'Choose reviewed, approved or declined.');
    const note = text(req.body, 'note', 1000);
    const record = await db.prepare('SELECT id FROM contributions WHERE id=?').get(req.params.id);
    if (!record) throw fail(404, 'Request not found.');
    await db.prepare('INSERT INTO worker_reviews (contribution_id,status,note,reviewed_by,reviewed_at) VALUES (?,?,?,?,?) ON DUPLICATE KEY UPDATE status=VALUES(status),note=VALUES(note),reviewed_by=VALUES(reviewed_by),reviewed_at=VALUES(reviewed_at)').run(record.id, req.body.status, note, req.worker.id, new Date().toISOString());
    res.json({ message: 'Review saved. Payment and sponsorship status have not changed.' });
  });
  router.get('/staff', admin, async (_req, res) => res.json({ staff: await db.prepare('SELECT u.id,u.username,u.email,w.role,w.granted_at FROM worker_access w JOIN users u ON u.id=w.user_id ORDER BY w.granted_at').all() }));
  router.post('/staff', admin, async (req, res) => {
    if (!['admin', 'editor', 'viewer'].includes(req.body.role) || typeof req.body.email !== 'string' || req.body.email.length > 254) throw fail(400, 'Choose an existing account email and role.');
    const user = await db.prepare('SELECT id FROM users WHERE email=?').get(req.body.email.trim().toLowerCase());
    if (!user) throw fail(404, 'That person must register an account on this deployment first.');
    if (user.id === req.worker.id) throw fail(400, 'You cannot change your own access.');
    await db.prepare('INSERT INTO worker_access (user_id,role,granted_at) VALUES (?,?,?) ON DUPLICATE KEY UPDATE role=VALUES(role)').run(user.id, req.body.role, new Date().toISOString());
    res.status(201).json({ message: 'Staff access saved.' });
  });
  router.delete('/staff/:id', admin, async (req, res) => {
    if (req.params.id === req.worker.id) throw fail(400, 'You cannot remove your own access.');
    await db.prepare('DELETE FROM worker_access WHERE user_id=?').run(req.params.id);
    res.status(204).end();
  });
  router.use((error, _req, res, next) => error.workerError ? res.status(error.status).json({ error: error.message }) : next(error));
  app.use('/api/worker', router);
  // Uploads are public animal photography only. No directory listing or arbitrary path access.
  app.use('/public/uploads', express.static(uploadDirectory(), { dotfiles: 'deny', index: false, setHeaders: res => res.set('X-Content-Type-Options', 'nosniff') }));
}
